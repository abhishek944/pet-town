import { buildPlayerCostumeMaterials } from "./build-player-costume-materials.js";
import { buildPlayerBellyPatch } from "./build-player-belly-patch.js";
import { buildPlayerShoulderStrap } from "./build-player-shoulder-strap.js";
import { buildPlayerSatchel } from "./build-player-satchel.js";
import { buildPlayerScarf } from "./build-player-scarf.js";
import { buildPlayerHood } from "./build-player-hood.js";
import { buildPlayerAcornHat } from "./build-player-acorn-hat.js";
import { buildPlayerFaceSurface } from "./build-player-face-surface.js";
import { buildPlayerHair } from "./build-player-hair.js";
import { buildPlayerEyes } from "./build-player-eyes.js";
import { buildPlayerFacialDetails } from "./build-player-facial-details.js";
import { buildPlayerLimbsAndTail } from "./build-player-limbs-and-tail.js";
import { buildPlayerGlider } from "./build-player-glider.js";
import { buildPlayerBlobShadow } from "./build-player-blob-shadow.js";
import { initializePlayerAnimationState } from "./initialize-player-animation-state.js";
/** Procedurally constructed Pip model, facial expressions and blended locomotion animation. */
import * as THREE from "three";
import { addPlayerRigGroup } from "../rig-builders/add-player-rig-group.js";
import { addPlayerEllipsoidMesh } from "../rig-builders/add-player-ellipsoid-mesh.js";
import { playerEllipsoidSurface } from "../geometry/player-ellipsoid-surface.js";
export function initializePlayerCharacter() {
  let materials;
  ({ materials } = buildPlayerCostumeMaterials.call(this));
  let root = (this.root = new THREE.Group());
  root.name = `player`;
  let squash = (this.squash = addPlayerRigGroup(root, 0, 0, 0, `squash`));
  let hips = (this.hips = addPlayerRigGroup(squash, 0, 0.34, 0, `hips`));
  let torso = (this.torso = addPlayerRigGroup(hips, 0, 0, 0, `torso`));
  let breath = (this.breath = addPlayerRigGroup(torso, 0, 0.02, 0, `breath`));
  addPlayerEllipsoidMesh(breath, materials.fur, 0.265, 1, 1, 0.93, 0, 0.15, 0);
  let chestSurface = new playerEllipsoidSurface([0, 0.15, 0], [0.265, 0.265, 0.2465]);
  let strapSurface = new playerEllipsoidSurface([0, 0.15, 0], [0.265, 0.265, 0.2465]);
  buildPlayerBellyPatch.call(this, chestSurface, breath, materials);
  buildPlayerShoulderStrap.call(this, chestSurface, strapSurface, breath, materials);
  buildPlayerSatchel.call(this, breath, materials);
  buildPlayerScarf.call(this, breath, materials);
  let neck = (this.neck = addPlayerRigGroup(breath, 0, 0.36, 0, `neck`));
  let head = (this.head = addPlayerRigGroup(neck, 0, 0.31, 0.01, `head`));
  buildPlayerHood.call(this, head, materials);
  buildPlayerAcornHat.call(this, head, materials);
  let faceSurface;
  ({ faceSurface } = buildPlayerFaceSurface.call(this, head, materials));
  buildPlayerHair.call(this, faceSurface, head, materials);
  buildPlayerEyes.call(this, faceSurface, head, materials);
  buildPlayerFacialDetails.call(this, faceSurface, head, materials);
  buildPlayerLimbsAndTail.call(this, breath, materials, hips);
  buildPlayerGlider.call(this, breath, materials, root);
  buildPlayerBlobShadow.call(this);
  initializePlayerAnimationState.call(this);
}

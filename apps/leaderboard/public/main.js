const metricNames = {
  total: "Total tokens",
  input: "Input tokens",
  output: "Output tokens",
  cache: "Cache hits",
  cost: "Estimated cost",
};
const descriptions = {
  total: "Input, output, cache read and cache write tokens combined.",
  input: "Fresh input tokens processed by the model.",
  output: "Tokens generated by the model, including its reasoning.",
  cache: "Previously seen input tokens served from cache.",
  cost: "Pi's calculated model cost estimate. Subscription charges may differ.",
};
let metric = "total";
const period = document.querySelector("#period");
const rows = document.querySelector("#leaderboard-rows");

function formatScore(value) {
  return metric === "cost"
    ? `$${(Number(value) / 1_000_000).toFixed(2)}`
    : new Intl.NumberFormat().format(Number(value));
}

function renderRows(data) {
  rows.replaceChildren();
  if (!data.length) {
    const row = rows.insertRow();
    const cell = row.insertCell();
    cell.colSpan = 4;
    cell.className = "empty";
    cell.textContent = "No activity here yet. The board is ready for its first villager.";
    return;
  }
  data.forEach((entry, index) => {
    const row = rows.insertRow();
    const rank = row.insertCell();
    rank.className = "rank";
    rank.textContent = String(index + 1).padStart(2, "0");
    const member = row.insertCell();
    member.className = "member";
    const avatar = document.createElement("img");
    avatar.src = entry.avatar_url;
    avatar.alt = "";
    avatar.loading = "lazy";
    const name = document.createElement("span");
    name.textContent = entry.display_name;
    const handle = document.createElement("small");
    handle.textContent = `@${entry.github_login}`;
    const identity = document.createElement("span");
    identity.className = "identity";
    identity.append(name, handle);
    member.append(avatar, identity);
    const messages = row.insertCell();
    messages.className = "messages";
    messages.textContent = new Intl.NumberFormat().format(Number(entry.requests));
    const score = row.insertCell();
    score.className = "score";
    score.textContent = formatScore(entry.score);
  });
}

async function loadBoard() {
  const response = await fetch(`/api/leaderboard?metric=${metric}&period=${period.value}`);
  if (!response.ok) throw new Error("Could not load leaderboard");
  renderRows((await response.json()).rows);
}

document.querySelectorAll("[data-metric]").forEach((button) =>
  button.addEventListener("click", async () => {
    metric = button.dataset.metric;
    document
      .querySelectorAll("[data-metric]")
      .forEach((item) => item.classList.toggle("selected", item === button));
    document.querySelector("#score-heading").textContent = metricNames[metric];
    document.querySelector("#metric-description").textContent = descriptions[metric];
    await loadBoard();
  }),
);
period.addEventListener("change", () => {
  document.querySelector("#period-note").textContent = {
    week: "Rolling 7 days",
    month: "Rolling 30 days",
    all: "All time",
  }[period.value];
  loadBoard().catch(showError);
});

function showError(error) {
  rows.innerHTML = `<tr><td colspan="4" class="empty">${error.message}</td></tr>`;
}

async function loadAccount() {
  const { user } = await (await fetch("/api/me")).json();
  if (!user) return;
  const account = document.querySelector("#account");
  const label = document.createElement("span");
  label.textContent = `@${user.github_login}`;
  const logout = document.createElement("button");
  logout.textContent = "Sign out";
  logout.addEventListener("click", async () => {
    await fetch("/api/logout", { method: "POST" });
    location.reload();
  });
  account.replaceChildren(label, logout);
  document.querySelector("#join-action").textContent = "You’re part of the village ✦";
  document.querySelector("#setup").hidden = false;
}

document.querySelector("#generate-token").addEventListener("click", async () => {
  const response = await fetch("/api/token", { method: "POST" });
  if (!response.ok) return;
  const { token } = await response.json();
  const config = JSON.stringify({ url: location.origin, token }, null, 2);
  document.querySelector("#config-json").textContent = config;
  document.querySelector("#token-result").hidden = false;
});
document.querySelector("#copy-config").addEventListener("click", async () => {
  await navigator.clipboard.writeText(document.querySelector("#config-json").textContent);
  document.querySelector("#copy-config").textContent = "Copied!";
});
document.querySelector("#revoke-tokens").addEventListener("click", async () => {
  if (!confirm("Disconnect all devices from the leaderboard?")) return;
  const response = await fetch("/api/token/revoke-all", { method: "POST" });
  if (response.ok)
    alert("All connection tokens were revoked. Remove the local configuration file too.");
});
document.querySelector("#delete-account").addEventListener("click", async () => {
  if (!confirm("Permanently delete your leaderboard profile and all reported usage?")) return;
  const response = await fetch("/api/account/delete", { method: "POST" });
  if (response.ok) location.reload();
});

loadBoard().catch(showError);
loadAccount().catch(() => {});
